package Activitats;

public class Act9 {

    public static void main(String[] args) {

        // Inicialitzem la variable x amb el valor 10
        int x = 10;

        // Sumem x amb ell mateix:
        // 10 + 10 = 20
        x = x + x;

        // Restem 5 al valor actual de x:
        // 20 - 5 = 15
        x = x - 5;

        // El valor final de x és 15
        System.out.println("El valor final de x és: " + x);
    }
}
